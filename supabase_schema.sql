-- ==============================================================================
-- 7. RECOVERY CHECK-INS TABLE & POLICIES
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.recovery_checkins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  sleep_hours DOUBLE PRECISION NOT NULL,
  resting_heart_rate INTEGER NOT NULL,
  hrv_ms DOUBLE PRECISION,
  soreness INTEGER NOT NULL CHECK (soreness >= 1 AND soreness <= 10),
  energy_level INTEGER NOT NULL CHECK (energy_level >= 1 AND energy_level <= 10),
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Indices for performance
CREATE INDEX IF NOT EXISTS idx_recovery_checkins_user_id ON public.recovery_checkins(user_id);
CREATE INDEX IF NOT EXISTS idx_recovery_checkins_created_at ON public.recovery_checkins(created_at DESC);

-- Table permissions
GRANT ALL ON TABLE public.recovery_checkins TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- Enable Row Level Security
ALTER TABLE public.recovery_checkins ENABLE ROW LEVEL SECURITY;

-- Clean up any previous policies to prevent duplicates
DROP POLICY IF EXISTS "Users can view their own recovery checkins" ON public.recovery_checkins;
DROP POLICY IF EXISTS "Users can insert their own recovery checkins" ON public.recovery_checkins;
DROP POLICY IF EXISTS "Users can update their own recovery checkins" ON public.recovery_checkins;
DROP POLICY IF EXISTS "Users can delete their own recovery checkins" ON public.recovery_checkins;

-- Create RLS Policies for authenticated users
CREATE POLICY "Users can view their own recovery checkins"
  ON public.recovery_checkins
  FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

CREATE POLICY "Users can insert their own recovery checkins"
  ON public.recovery_checkins
  FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update their own recovery checkins"
  ON public.recovery_checkins
  FOR UPDATE
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can delete their own recovery checkins"
  ON public.recovery_checkins
  FOR DELETE
  TO authenticated
  USING (auth.uid() = user_id);
