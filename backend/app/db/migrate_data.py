"""Data migration utility from local SQLite recovery.db to Supabase PostgreSQL.

Features:
- Idempotent: Can be run multiple times safely without duplicate records.
- Preserves IDs, timestamps, values, and telemetry metrics.
- Validates source and destination record counts and samples.
- Sanitizes connection strings to prevent credential exposure.
"""

import os
import sqlite3
from datetime import datetime
from typing import Dict, Any, List
from sqlalchemy import create_engine, text, inspect
from app.core.config import settings


def migrate_sqlite_to_postgres(sqlite_path: str = "recovery.db", postgres_url: str | None = None) -> Dict[str, Any]:
    """Migrate recovery_checkins from SQLite to PostgreSQL.
    
    Returns:
        Summary dict containing status, counts, and details.
    """
    pg_url = postgres_url or settings.DATABASE_URL
    if pg_url.startswith("sqlite"):
        return {
            "success": False,
            "error": "Target database is configured as SQLite. Migration requires a PostgreSQL target.",
        }

    if not os.path.exists(sqlite_path):
        return {
            "success": False,
            "error": f"Source SQLite file '{sqlite_path}' does not exist.",
        }

    # 1. Read SQLite records
    sqlite_conn = sqlite3.connect(sqlite_path)
    sqlite_conn.row_factory = sqlite3.Row
    try:
        cur = sqlite_conn.cursor()
        cur.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='recovery_checkins';")
        if not cur.fetchone():
            return {
                "success": False,
                "error": "Table 'recovery_checkins' not found in source SQLite database.",
            }
        
        cur.execute("SELECT id, sleep_hours, resting_heart_rate, hrv_ms, soreness, energy_level, created_at FROM recovery_checkins ORDER BY id ASC;")
        source_rows = [dict(r) for r in cur.fetchall()]
        source_count = len(source_rows)
    finally:
        sqlite_conn.close()

    # 2. Connect to PostgreSQL
    engine = create_engine(pg_url, pool_pre_ping=True)
    inserted_count = 0
    skipped_count = 0

    try:
        with engine.begin() as conn:
            # Check if destination table exists
            inspector = inspect(conn)
            tables = inspector.get_table_names()
            if "recovery_checkins" not in tables:
                # Create table if not present
                conn.execute(text("""
                    CREATE TABLE IF NOT EXISTS public.recovery_checkins (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id UUID,
                        sleep_hours DOUBLE PRECISION NOT NULL,
                        resting_heart_rate INTEGER NOT NULL,
                        hrv_ms DOUBLE PRECISION,
                        soreness INTEGER NOT NULL CHECK (soreness >= 1 AND soreness <= 10),
                        energy_level INTEGER NOT NULL CHECK (energy_level >= 1 AND energy_level <= 10),
                        created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
                    );
                """))

            # Fetch existing records to prevent duplicates
            existing_ids = set()
            existing_rows = conn.execute(text("SELECT id FROM public.recovery_checkins;")).fetchall()
            for r in existing_rows:
                existing_ids.add(r[0])

            # Insert new rows
            for row in source_rows:
                row_id = row["id"]
                if row_id in existing_ids:
                    skipped_count += 1
                    continue
                
                # Parse timestamp if string
                created_at_val = row["created_at"]
                if isinstance(created_at_val, str):
                    try:
                        created_at_val = datetime.fromisoformat(created_at_val)
                    except ValueError:
                        pass

                conn.execute(
                    text("""
                        INSERT INTO public.recovery_checkins 
                        (id, user_id, sleep_hours, resting_heart_rate, hrv_ms, soreness, energy_level, created_at)
                        VALUES (:id, NULL, :sleep_hours, :resting_heart_rate, :hrv_ms, :soreness, :energy_level, :created_at)
                    """),
                    {
                        "id": row_id,
                        "sleep_hours": row["sleep_hours"],
                        "resting_heart_rate": row["resting_heart_rate"],
                        "hrv_ms": row["hrv_ms"],
                        "soreness": row["soreness"],
                        "energy_level": row["energy_level"],
                        "created_at": created_at_val,
                    }
                )
                inserted_count += 1

            # Update PostgreSQL sequence to avoid PK collisions with future auto-generated IDs
            if source_rows:
                max_id = max(r["id"] for r in source_rows)
                conn.execute(text(f"""
                    SELECT setval(
                        pg_get_serial_sequence('public.recovery_checkins', 'id'),
                        COALESCE((SELECT MAX(id) FROM public.recovery_checkins), 1),
                        true
                    );
                """))

            # Verify total count in target
            target_count = conn.execute(text("SELECT count(*) FROM public.recovery_checkins;")).scalar()

        return {
            "success": True,
            "source_records": source_count,
            "inserted_records": inserted_count,
            "skipped_records": skipped_count,
            "target_total_records": target_count,
        }

    except Exception as e:
        err_msg = str(e)
        if "@" in err_msg and "://" in err_msg:
            import re
            err_msg = re.sub(r"://[^@]+@", "://***:***@", err_msg)
        return {
            "success": False,
            "error": err_msg,
        }
    finally:
        engine.dispose()


if __name__ == "__main__":
    result = migrate_sqlite_to_postgres()
    print("=" * 60)
    print("REVORA RECOVERY DATA MIGRATION")
    print("=" * 60)
    for k, v in result.items():
        print(f"  {k}: {v}")
    print("=" * 60)
